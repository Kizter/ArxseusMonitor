/** Glyph status: centang, segitiga peringatan, silang, jam. */
export function LevelGlyph({
  level,
  className,
}: IconProps & { level: Level }) {
  const common = {
    "aria-hidden": true,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 1.8,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    className,
  };

  switch (level) {
    case "safe":
      return (
        <svg {...common}>
          <circle cx="12" cy="12" r="9" />
          <path d="m8.5 12.2 2.5 2.5 4.6-5.1" />
        </svg>
      );
    case "warn":
      return (
        <svg {...common}>
          <path d="M12 4.2 21 20H3z" />
          <path d="M12 9.5v4.4" />
          <path d="M12 17.2h.01" />
        </svg>
      );
    case "danger":
      return (
        <svg {...common}>
          <circle cx="12" cy="12" r="9" />
          <path d="m9.2 9.2 5.6 5.6M14.8 9.2l-5.6 5.6" />
        </svg>
      );
    default:
      return (
        <svg {...common}>
          <circle cx="12" cy="12" r="9" />
          <path d="M12 7.5V12l3 1.8" />
        </svg>
      );
  }
}
